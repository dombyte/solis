// Helper functions
function getDataObjectById(id: string): ApiDataObject | undefined {
  return apiDataObjects.find(obj => obj.id === id);
}

/**
 * Get the source path for a given internal ID
 */
export function getSourceById(id: string): string | undefined {
  const obj = getDataObjectById(id);
  return obj?.source;
}
