import type { ApiDataObject } from '../../types';

/** One energy series; it exists at every level (same series as `energyKinds()` in
 *  internal/solis/table.go, plus the net grid value). */
interface EnergyKind {
  key: string;         // API key prefix, e.g. 'grid_import'
  id: string;          // internal id prefix, e.g. 'energy_imported'
  name: string;
  description: string; // completed by the level's phrase
  note?: string;       // appended after the level's phrase
  order: number;       // position inside each energy group
}

const ENERGY_KINDS: EnergyKind[] = [
  { key: 'pv_energy', id: 'pv_energy', name: 'PV', description: 'Solar energy generated by the PV panels', order: 1 },
  { key: 'household_energy', id: 'household_energy', name: 'Household', description: 'Energy consumed by household loads', order: 2 },
  { key: 'backup_energy', id: 'backup_energy', name: 'Backup', description: 'Energy consumed by loads on the backup output', order: 3 },
  { key: 'energy_consumption', id: 'energy_consumption', name: 'Energy Consumption', description: 'Energy consumed by all loads (household and backup)', order: 4 },
  { key: 'grid_export', id: 'energy_fed', name: 'Grid Export', description: 'Energy fed into the grid', order: 5 },
  { key: 'grid_import', id: 'energy_imported', name: 'Grid Import', description: 'Energy imported from the grid', order: 6 },
  { key: 'grid_energy', id: 'grid_energy', name: 'Grid (Net)', description: 'Net grid energy (export − import)', note: ': positive = net export, negative = net import', order: 7 },
  { key: 'battery_discharge', id: 'battery_discharge', name: 'Battery Discharge', description: 'Energy discharged from the battery', order: 8 },
  { key: 'battery_charge', id: 'battery_charge', name: 'Battery Charge', description: 'Energy charged into the battery', order: 9 },
];

/** The four levels of every energy series: key suffix, id suffix and description phrase. */
const ENERGY_LEVELS = [
  { level: 'daily', id: 'today', phrase: 'today' },
  { level: 'monthly', id: 'month', phrase: 'this month' },
  { level: 'yearly', id: 'year', phrase: 'this year' },
  { level: 'total', id: 'total', phrase: 'since monitoring started' },
];

/** One energy series across the dashboard columns (Today, This Month, This Year, Total). */
export interface EnergyRow {
  name: string;
  /** Level-free explanation of the series. */
  description: string;
  /** Internal ids per level, in the order of the energy dashboard groups. */
  ids: string[];
}

/** The energy series as rows of the dashboard's energy table and cards. */
export const ENERGY_ROWS: EnergyRow[] = ENERGY_KINDS.map(k => ({
  name: k.name,
  description: `${k.description}${k.note ?? ''}`,
  ids: ENERGY_LEVELS.map(l => `${k.id}_${l.id}`),
}));

/** Builds the kind x level energy objects (e.g. `grid_import_monthly`). */
function energyObjects(): ApiDataObject[] {
  return ENERGY_LEVELS.flatMap(l =>
    ENERGY_KINDS.map(k => ({
      key: `${k.key}_${l.level}`,
      id: `${k.id}_${l.id}`,
      name: k.name,
      description: `${k.description} ${l.phrase}${k.note ?? ''}`,
      unit: 'kWh',
      source: `/api/data/${k.key}_${l.level}`,
      category: 'energy',
      group: `energy_${l.level}`,
      format: 'energy' as const,
      precision: 2,
      order: k.order,
    })),
  );
}

